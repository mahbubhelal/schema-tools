<?php

declare(strict_types=1);

namespace Mahbub\SchemaTools\Support;

use Illuminate\Support\Facades\Config;
use InvalidArgumentException;
use UnexpectedValueException;

/**
 * The single source of truth for which source tables and views the project
 * relies on, per connection, read from two places: the `sources` each
 * connection lists in `schema-tools.php` (manual, never written by a command)
 * and `<schema path>/source-tables.php`, which `schema:detect` owns and
 * rewrites whole on every run.
 */
final class Manifest
{
    public function path(): string
    {
        return Config::string('schema-tools.paths.schema') . '/source-tables.php';
    }

    public function load(): ManifestData
    {
        return new ManifestData(manual: $this->manual(), generated: $this->generated());
    }

    /**
     * Serialise the generated names to a Pint-clean PHP file, replacing it.
     */
    public function write(ManifestData $manifestData): void
    {
        $body = $this->body($manifestData->generated);
        $array = $body === '' ? '[]' : "[\n{$body}]";

        $contents = <<<PHP
            <?php

            declare(strict_types=1);

            /**
             * Source tables and views the code relies on, per database connection.
             *
             * Generated by `php artisan schema:detect`, which rewrites this file on every
             * run. Do not edit it: list what the detector cannot see as `sources` in
             * `schema-tools.php` instead.
             *
             * @return array<string, list<string>>
             */

            return {$array};

            PHP;

        file_put_contents($this->path(), rtrim($contents, "\n") . "\n");
    }

    /**
     * @return array<string, list<string>>
     */
    private function manual(): array
    {
        $manual = [];

        foreach (Config::array('schema-tools.connections') as $connection => $settings) {
            if (!is_array($settings)) {
                throw new InvalidArgumentException("`connections.{$connection}` in schema-tools.php must be an array of settings.");
            }

            if (array_key_exists('sources', $settings)) {
                $manual[(string) $connection] = $this->names($settings['sources'])
                    ?? throw new InvalidArgumentException("`connections.{$connection}.sources` in schema-tools.php must be a list of table and view names.");
            }
        }

        return $manual;
    }

    /**
     * @return array<string, list<string>>
     */
    private function generated(): array
    {
        $path = $this->path();

        if (!is_file($path)) {
            return [];
        }

        $generated = require $path;

        if (!is_array($generated)) {
            throw $this->invalidGeneratedManifest($path);
        }

        $namesPerConnection = [];

        foreach ($generated as $connection => $names) {
            if (!is_string($connection)) {
                throw $this->invalidGeneratedManifest($path);
            }

            $namesPerConnection[$connection] = $this->names($names) ?? throw $this->invalidGeneratedManifest($path);
        }

        return $namesPerConnection;
    }

    /**
     * The names in order, or null when the value is not an array of strings.
     *
     * @return list<string>|null
     */
    private function names(mixed $value): ?array
    {
        if (!is_array($value)) {
            return null;
        }

        $names = [];

        foreach ($value as $name) {
            if (!is_string($name)) {
                return null;
            }

            $names[] = $name;
        }

        return $names;
    }

    private function invalidGeneratedManifest(string $path): UnexpectedValueException
    {
        return new UnexpectedValueException("`{$path}` must return a list of table and view names per connection; run `php artisan schema:detect` to rebuild it.");
    }

    /**
     * @param  array<string, list<string>>  $names
     */
    private function body(array $names): string
    {
        $body = '';

        foreach ($names as $connection => $list) {
            $body .= "    '{$connection}' => [\n";

            foreach ($list as $name) {
                $body .= "        '{$name}',\n";
            }

            $body .= "    ],\n";
        }

        return $body;
    }
}
